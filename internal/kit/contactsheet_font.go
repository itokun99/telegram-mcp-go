var solidGlyph = [glyphColumns]byte{0x7f, 0x7f, 0x7f, 0x7f, 0x7f}

// drawLabel rasterises label with its top-left corner at origin, clipping
// anything that would leave the cell. It is the Go stand-in for the Python
// draw.text call in _draw_cell.
func drawLabel(sheet *image.RGBA, origin image.Point, label string) {
	advance := (glyphColumns + glyphGap) * labelScale
	pen := origin

	for _, letter := range strings.ToUpper(label) {
		if pen.X+glyphColumns*labelScale > sheet.Bounds().Max.X {
			return
		}
		if pen.Y+glyphRows*labelScale > sheet.Bounds().Max.Y {
			return
		}
		glyph, ok := labelGlyphs[letter]
		if !ok {
			if !unicode.IsPrint(letter) {
				continue
			}
			glyph = solidGlyph
		}
		stampGlyph(sheet, pen, glyph)
		pen.X += advance
	}
}

func stampGlyph(sheet *image.RGBA, origin image.Point, glyph [glyphColumns]byte) {
	for column := 0; column < glyphColumns; column++ {
		for row := 0; row < glyphRows; row++ {
			if glyph[column]&(1<<row) == 0 {
				continue
			}
			draw.Draw(
				sheet,
				image.Rect(
					origin.X+column*labelScale,
					origin.Y+row*labelScale,
					origin.X+(column+1)*labelScale,
					origin.Y+(row+1)*labelScale,
				),
				image.NewUniform(LabelForeground),
				image.Point{},
				draw.Src,
			)
		}
	}
}
