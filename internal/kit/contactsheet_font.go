package kit

// This file carries the 5x7 bitmap font the contact-sheet labels are drawn
// with. Pillow's ImageFont.load_default(size=15) has no standard-library Go
// equivalent (golang.org/x/image/font is not an allowed dependency), so labels
// are rasterised from the table below. Cell labels in practice are numeric
// photo/message identifiers, which the digit glyphs cover; lowercase input is
// folded to uppercase and anything unlisted renders as a solid block, so a
// label is never silently dropped.

import (
	"image"
	"image/draw"
	"strings"
	"unicode"
)

const (
	glyphColumns = 5
	glyphRows    = 7
	glyphGap     = 1
)

// labelScale fits the 7-row cell into the label strip under LabelPaddingPixels
// of inset: (26 - 2*5) / 7 = 2.
var labelScale = max(1, (LabelStripPixels-2*LabelPaddingPixels)/glyphRows)

